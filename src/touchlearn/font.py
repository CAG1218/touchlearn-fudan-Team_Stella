def _glyph(character: str) -> tuple[tuple[Point, ...], ...]:
    return STROKES.get(character.upper(), STROKES["?"])


def stroke_width(height: float) -> float:
    return max(1.0, height / 5.0)


def text_width(text: str, height: float) -> float:
    if not text:
        return 0.0
    unit = height / 5.0
    return (4 * len(text) - 1) * unit


def text_strokes(text: str, x: float, y: float, height: float) -> list[tuple[Point, ...]]:
    """Return stroke polylines in millimetres."""
    unit = height / 5.0
    result: list[tuple[Point, ...]] = []
    for char_index, character in enumerate(text):
        origin_x = x + char_index * 4 * unit
        for stroke in _glyph(character):
            result.append(tuple((origin_x + px * unit, y + py * unit) for px, py in stroke))
    return result


def text_bbox(text: str, x: float, y: float, height: float) -> tuple[float, float, float, float]:
    pad = stroke_width(height) / 2.0
    return (x - pad, y - pad, text_width(text, height) + 2.0 * pad, height + 2.0 * pad)
